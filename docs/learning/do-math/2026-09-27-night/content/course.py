def _mapping(path):
    if path in DOC_MAP: return DOC_MAP[path]
    name=Path(path).stem
    if path.startswith('scripts/tests/'):
        if name.endswith('_fixtures'): return ('시험의 시작 상태·러너·기록을 공유하는 fixture',[25])
        stem=name.removeprefix('test_')
        if stem in MODULE_MAP:
            purpose,nums=MODULE_MAP[stem]; return ('회귀 검사: '+purpose,sorted(set(nums+[25])))
        clusters=[(('formal','lean','trust','environment'),[16]),(('review','reassessment','impact'),[15,17]),
                  (('submission','native_final'),[14]),(('currentness','role_input','context','input_'),[13]),
                  (('task','contract','planning','repetition','revision','reading_map'),[7,8,9,15]),
                  (('operator','schedule','installation'),[21]),(('academic','goal','purpose','completion'),[18]),
                  (('knowledge','relation'),[3,4]),(('provider','model','session','machine'),[10,23]),
                  (('observation','control','checkpoint','stop'),[19,20]),(('unicode','intent','governance','delegation','question'),[5,6]),
                  (('launch','process','job','recovery','lifecycle','temporary'),[20]),(('record','repository','payload','digest','file_io','report'),[22,24])]
        for keys,nums in clusters:
            if any(key in stem for key in keys): return ('성질별 회귀 검사: '+stem,sorted(set(nums+[25])))
        return ('성질별 회귀 검사: '+stem,[24,25])
    if name in MODULE_MAP: return MODULE_MAP[name]
    raise ValueError('File has no responsibility mapping: '+path)

