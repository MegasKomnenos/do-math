def main():
    dry = "--dry" in sys.argv
    t = io.open(CH, encoding="utf-8").read()
    bad = 0
    tally = {}
    for i, (old, new, sec, kind) in enumerate(E, 1):
        n = t.count(old)
        if n != 1:
            bad += 1
            print(f"[{i}] 원문 조각이 {n}번 나타남: {old[:60]!r}")
        else:
            t = t.replace(old, new, 1)
            tally.setdefault(kind, {}); tally[kind][sec] = tally[kind].get(sec, 0) + 1
    if bad:
        print(f"어긋난 조각 {bad}개 — 아무것도 쓰지 않음")
        sys.exit(1)
    for k, d in tally.items():
        print(f"{k}: 절별 {dict(sorted(d.items()))} 합 {sum(d.values())}")
    if dry:
        print(f"모든 조각 일치({len(E)}개); --dry라 쓰지 않음")
        return
    io.open(CH, "w", encoding="utf-8", newline="\n").write(t)
    print(f"적용 {len(E)}개")


if __name__ == "__main__":
    main()
