# 정리 5.18 머리에 계산 보조 덧붙임
p = "임시/주차함수_증명/장/장5B.md"
s = io.open(p, encoding="utf-8").read()
lines = s.split("\n")
idx = [i for i, ln in enumerate(lines) if ln.startswith("**정리 {{old:정리 5.18}}") and "의 증명" not in ln]
assert len(idx) == 1, idx
ln = lines[idx[0]]
print("before:", ln[:160])
assert ln.count("[비형식 증명;") == 1, ln
lines[idx[0]] = ln.replace("[비형식 증명;", "[비형식 증명, 계산 보조(방향 반올림 구간);", 1)
print("after: ", lines[idx[0]][:160])
io.open(p, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("patched", p)
