def main():
    s = io.open(P, encoding="utf-8").read()
    i = s.find("### 1.4 "); j = s.find("### 1.5 ")
    sec = s[i:j]
    # 문단 머리의 굵은 소제목 제거(진술 머리 `**정리 {{…}}`는 제외)
    new_sec, n = re.subn(r"(?m)^\*\*(?!(?:정의|정리|명제|보조정리|따름정리) \{\{)[^*\n]{1,40}\.\*\* ", "", sec)
    for old, new in LINKS:
        if old in new_sec:
            new_sec = new_sec.replace(old, new, 1)
        elif new not in new_sec:
            print("앵커 없음:", old[:40])
    print("소제목 제거", n)
    if DRY:
        print(new_sec[:600]); return
    io.open(P, "w", encoding="utf-8", newline="\n").write(s[:i] + new_sec + s[j:])
    print("기록함")


if __name__ == "__main__":
    main()
