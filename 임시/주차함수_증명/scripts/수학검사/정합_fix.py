def read(path):
    with open(path, "rb") as f:
        raw = f.read()
    return raw.decode("utf-8")


def write(path, text):
    with open(path, "wb") as f:
        f.write(text.encode("utf-8"))


def main():
    texts = {p: read(p) for p in {LEDGER, DEP, STRUCT, APPA}}
    applied, skipped, failed = [], [], []
    for eid, path, old, new, marker in EDITS:
        t = texts[path]
        mk = marker if marker is not None else new
        if mk in t and old not in t:
            skipped.append(eid); continue
        if marker is not None and mk in t and old in t:
            # 삽입형 편집: 앵커는 남아 있으나 새 행이 이미 들어 있음
            skipped.append(eid); continue
        c = t.count(old)
        if c != 1:
            failed.append((eid, c)); continue
        texts[path] = t.replace(old, new, 1)
        applied.append(eid)
    if failed:
        for eid, c in failed:
            print(f"[실패] {eid}: 앵커 {c}회", file=sys.stderr)
        print("아무것도 쓰지 않았다.", file=sys.stderr)
        return 1
    for p, t in texts.items():
        if t != read(p):
            write(p, t)
    for eid in applied:
        print(f"[적용] {eid}")
    for eid in skipped:
        print(f"[이미 적용됨] {eid}")
    print(f"적용 {len(applied)}, 이미 적용 {len(skipped)}, 실패 {len(failed)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
