    t = io.open(CH, encoding="utf-8").read()
    bad = 0
    tally = {}
    for i, (old, new, sec, idx) in enumerate(E, 1):
        n = t.count(old)
        if n != 1:
            bad += 1
            print(f"[{i}] 원문 조각이 {n}번 나타남: {old[:60]!r}")
        else:
            t = t.replace(old, new, 1)
