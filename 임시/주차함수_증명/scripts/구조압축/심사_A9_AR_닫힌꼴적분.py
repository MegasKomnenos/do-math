# A9 추가 발견 검산: 정리 9.23(AR) (1)의 두 적분 J1,J2는 초등 닫힌 꼴로 적힌다.
#  int (a+t)^{-7/2} dt = (2/5)[(a+A)^{-5/2}-(a+B)^{-5/2}];
#  int (a+t)^{-7/2} t^{-3/2} dt : t=a u/(1-u) => a^{-4} int u^{-3/2}(1-u)^3 du = a^{-4}[-2u^{-1/2}-6u^{1/2}+2u^{3/2}-(2/5)u^{5/2}]
# 비교: 부록 D.AR-integrals의 구간 J1 in [0.432680,0.432707], J2 in [0.432831,0.432857], L*(6668) in [1.20601,1.20607].
from math import sqrt
def F1(a,t): return -(2/5)*(a+t)**-2.5
def F2(a,t):
    u=t/(a+t); return a**-4*(-2*u**-0.5-6*u**0.5+2*u**1.5-(2/5)*u**2.5)
def J(a,c,A,B):
    return (F1(a,B)-F1(a,A)) - c*(F2(a,B)-F2(a,A))
def Lstar(k):
    # 본문 J1 = 5/2 int_{1/k}^{1} (1+t+2/k)^{-7/2} (1-3k^{-1/2}(t-1/k)^{-3/2})_+ dt ; s=t-1/k: (1+3/k+s)^{-7/2}(1-c1 s^{-3/2}), s in [c1^{2/3}, 1-1/k]
    c1=3*k**-0.5
    J1=2.5*J(1+3/k,c1,c1**(2/3),1-1/k)
    # 본문 J2 = 5/2 int_{1/k}^{(k-1)/k} (1+t+1/k)^{-7/2} (1-3(k-1)k^{-3/2}(t-1/k)^{-3/2})_+ dt ; s=t-1/k: (1+2/k+s)^{-7/2}, s in [c2^{2/3}, (k-2)/k]
    c2=3*(k-1)*k**-1.5; J2=2.5*J(1+2/k,c2,c2**(2/3),(k-2)/k)
    J3=(k/(2*k+1))**2.5*(1-3*k**-0.5); J4=(k/(2*k+1))**2.5*(1-3*(k-1)**-0.5)
    return J1,J2,J3,J4,J1+J2+J3+J4
for k in (6668,10**4,13336,10**5,10**6,10**7):
    J1,J2,J3,J4,L=Lstar(k)
    print("k=%d: J1=%.6f J2=%.6f J3=%.7f J4=%.7f L*=%.6f"%(k,J1,J2,J3,J4,L))
