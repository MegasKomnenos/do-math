assert s.count(old) == 1, s.count(old)
new = old + r" 뒤의 장들은 「열 $k$」를 이웃한 두 열의 비교 $b_{n,k-1}$ 대 $b_{n,k}$가 놓인 자리, 곧 용량 $k$(2.6절에서 정의하는 $k=\ell+1$)의 열이라는 뜻으로도 쓴다. 그 뜻의 열 $k$는 수준 $k-1$을 고정한 이 절의 열과 한 칸 어긋나며, 두 뜻의 관계는 3.4절에서 정한다."
s = s.replace(old, new)
