# -*- coding: utf-8 -*-
"""셋째 독해의 세션 몫 수리: 1.3 「열 k」 선행 안내, 1.4 유한 확인의 범위 밖 수용 문장, 9.1 집필 맥락 낱말 제거."""
import io


def rw(p):
    return io.open(p, encoding="utf-8").read()


def wr(p, s):
    io.open(p, "w", encoding="utf-8", newline="\n").write(s)


root = "임시/주차함수_증명"

# 9.1
p = root + "/장/장9.md"
s = rw(p)
old = "구조표가 처음부터 진술만 두기로 한 것과 집필에서 진술만 두게 된 것을 함께 넣었고, 합의에 따라 식과 상수표만 옮기지 않은 자리(포락선·봉투·적분의 식)도 넣었다."
assert s.count(old) == 1, s.count(old)
new = "이 글이 처음부터 진술만 두기로 한 결과와 쓰는 과정에서 진술만 두게 된 결과를 함께 넣었고, 증명은 실었으나 식과 상수표만 옮기지 않은 자리(봉투·적분의 식과 계수표)도 넣었다."
s = s.replace(old, new)
wr(p, s)
print("9.1 patched")

# 1.3 열 선행 안내
p = root + "/장/장1.md"
