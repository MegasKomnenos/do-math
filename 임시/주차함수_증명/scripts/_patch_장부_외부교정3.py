def main():
    s = io.open(P, encoding="utf-8").read()
    done = 0
    for old, new in EDITS:
        n = s.count(old)
        if n == 0:
            if new in s:
                print("이미 반영:", old[:40])
                continue
            print("원문 없음:", old[:60])
            sys.exit(1)
        if n != 1:
            print(f"원문 {n}곳(1이어야 함):", old[:60])
            sys.exit(1)
        s = s.replace(old, new)
        done += 1
    print("치환", done)
    if not DRY:
        io.open(P, "w", encoding="utf-8", newline="\n").write(s)


if __name__ == "__main__":
    main()
