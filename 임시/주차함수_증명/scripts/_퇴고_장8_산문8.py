def main():
    dry = "--dry" in sys.argv
    texts = {p: io.open(p, encoding="utf-8").read() for p in {CH, AP}}
    bad = 0
    tally = {}
    for i, (p, old, new, sec, crit) in enumerate(E, 1):
        n = texts[p].count(old)
        if n != 1:
            bad += 1
            print(f"[{i}] {os.path.basename(p)}: 원문 조각이 {n}번 나타남: {old[:60]!r}")
        else:
            texts[p] = texts[p].replace(old, new, 1)
            tally.setdefault(crit, {}); tally[crit][sec] = tally[crit].get(sec, 0) + 1
    if bad:
        print(f"어긋난 조각 {bad}개 — 아무것도 쓰지 않음")
        sys.exit(1)
    for c, d in tally.items():
        print(f"기준 {c}: 절별 {dict(sorted(d.items()))} 합 {sum(d.values())}")
    if dry:
        print(f"모든 조각 일치({len(E)}개); --dry라 쓰지 않음")
        return
    for p, t in texts.items():
        io.open(p, "w", encoding="utf-8", newline="\n").write(t)
    print(f"적용 {len(E)}개")


if __name__ == "__main__":
    main()
