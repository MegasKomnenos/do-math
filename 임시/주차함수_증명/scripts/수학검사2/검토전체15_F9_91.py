    G=Phi+u*(0.5320*c1*xi**1.5+0.2)
    E=c1*(1+il)*(0.5320*xi**1.5*u+0.7979*sqrt(xi)*u**3+c1*(0.625*xi**2+xi*u**2))/(0.7978*sqrt(xi)-0.8848*u)
