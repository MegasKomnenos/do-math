def main():
    applied = skipped = 0
    for rel, old, new, why in EDITS:
        path = os.path.join(ROOT, rel)
        with io.open(path, encoding="utf-8") as f:
            s = f.read()
        n_old, n_new = s.count(old), s.count(new)
        if n_new == 1:          # 이미 적용(new가 old를 품는 경우도 포함)
            skipped += 1
            continue
        if n_old != 1:
            print(f"[중단] {rel}: 앵커가 {n_old}번 나타남: {old[:60]}")
            sys.exit(1)
        s = s.replace(old, new)
        with io.open(path, "w", encoding="utf-8", newline="") as f:
            f.write(s)
        applied += 1
        print(f"[적용] {rel}: {old[:50]} -> {new[:50]}  ({why[:60]})")
    print(f"적용 {applied}, 이미 적용 {skipped}")


if __name__ == "__main__":
    main()
