def mid(Y):
    q = floor(6*Y**(2/3) + 1e-9)
    # exact floor check
    while (q+1)**3 <= 216*Y*Y: q += 1
    while q**3 > 216*Y*Y: q -= 1
    s = sum(min(1.0, 1.15*(Y+j+1)/(j+1)**1.5) for j in range(1, q))
    return 1 - 2/Y - (1-(q+1)/Y)*1.15*(Y+q+1)/(q+1)**1.5 - s/Y
