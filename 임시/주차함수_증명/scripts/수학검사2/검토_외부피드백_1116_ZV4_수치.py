"""ZV4 검산. (A) 부록 D xcert-partAB 범위 3의 꼬리 수열 y_n = n^j pr°_n e^{γ n}의 모양(이웃비·골짜기)과 Abel/TV 상계.
(B) 9장 정리 head-sum-1 6단계와 9장의 소수 등호 전부를 mpmath 50자리로 다시 센다. python -I 로 실행."""
from mpmath import mp, mpf, e, pi, sqrt, exp, log, power, nstr
mp.dps = 50
print("=== (A) 범위 3 꼬리 수열의 모양 ===")
def ratio(n, j, g):   # y_{n+1}/y_n, y_n = n^j (n-1)^{n-1} e^{-n}/n! e^{g n}
    n = mpf(n)
    return power(1+1/n, j-1) * power(1+1/(n-1), n-1) * exp(g-1)
# (1+1/n)(1+1/(n-1))^{n-1} > e ?  n=2..1000 및 큰 n
mn = min(power(1+1/mpf(n), 1)*power(1+1/mpf(n-1), n-1)/e for n in list(range(2, 2000)) + [10**4, 10**5, 7*10**5])
print("min_n (1+1/n)(1+1/(n-1))^{n-1}/e over n in [2,2000]∪{1e4,1e5,7e5} =", nstr(mn, 12), "(>1 이면 j>=2 수열은 γ>=0에서 증가)")
# 이웃비의 단조성(j=0,1): n=257..k 에서 ratio(n+1) > ratio(n) 표본
for j in (0, 1):
    inc = all(ratio(n+1, j, 0) > ratio(n, j, 0) for n in list(range(257, 3000)) + [10**4, 10**5-1])
    print(f"j={j}: 이웃비가 n에 증가(표본 n=257..3000,1e4,1e5-1):", inc)
# 실제 범위 3의 k와 ς_L 대략값으로 모양 판정
for k, sig in ((10**5, mpf('7.7')), (10**5, mpf('9.0')), (7*10**5, mpf('9.0')), (7*10**5, mpf('12'))):
    g = sig / k
    for j in (0, 1, 2):
        r0 = ratio(257, j, g); rk = ratio(k-1, j, g)
        shape = "증가(단조)" if r0 >= 1 else ("골짜기(감소→증가)" if rk > 1 else "감소(단조)")
        print(f"k={k}, ς={sig}, j={j}: 비(257)={nstr(r0,8)}, 비(k-1)={nstr(rk,8)} → {shape}")
# 골짜기 수열의 TV와 Abel 상계: 작은 예(k=3000, ς=6)로 수치 확인
import mpmath
k = 3000; g = mpf(6)/k
for j in (0, 1, 2):
    ys = []
    y = mpf(257)**j * power(256, 256) * exp(-257) / mpmath.factorial(257) * exp(g*257)
    ys.append(y)
    for n in range(257, k):
        y = y * ratio(n, j, g); ys.append(y)
    tv = sum(abs(ys[i+1]-ys[i]) for i in range(len(ys)-1))
    print(f"k=3000 ς=6 j={j}: TV={nstr(tv,8)}, y_257+y_k={nstr(ys[0]+ys[-1],8)}, TV<=y_257+y_k: {tv <= ys[0]+ys[-1]+mpf(10)**-40}, 2y_k={nstr(2*ys[-1],8)}, TV<=y_k(j>=2용): {tv<=ys[-1]+mpf(10)**-40}",
          " 봉우리꼴이면 TV=2max-y_a-y_b=", nstr(2*max(ys)-ys[0]-ys[-1], 8), " argmin idx=", ys.index(min(ys))+257)
    # Abel 상계 실제 검증: theta=0.01
    th = mpf('0.01')
    S = sum(ys[i]*exp(1j*(257+i)*th) for i in range(len(ys)))
    print(f"   |Σ y_n e^{{inθ}}|(θ=0.01)={nstr(abs(S),8)} <= (y_257+2y_k)/sin(θ/2)={nstr((ys[0]+2*ys[-1])/mpmath.sin(th/2),8)}")

