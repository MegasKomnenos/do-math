def show(name, val, text, note=""):
    v = mpf(text)
    rel = "=" if val == v else ("<표시값(표시가 올림)" if val < v else ">표시값(표시가 내림)")
    print(f"{name}: 참값 {nstr(val, 14)} | 본문 {text} | {rel} | 차 {nstr(val - v, 3)} {note}")
