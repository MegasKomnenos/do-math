# ---- closed-form-envelope (라) 이음새 (부록 D 인증; 참고로 50자리 재계산) ----
def pieces(x, k):
    q = x * k ** (mpf(2) / 3)
    p = q - 1
    n = k + q
    kk = k + 1
    eps = k ** (-mpf(1) / 3)
    E = 2 * C * exp(-1 / (12 * q)) / sqrt(x) * (1 + x * eps)
    R1 = mpf("1.5") * C * (2 * sqrt(p) - 1) / k ** (mpf(2) / 3)
    H = mpf(2) / 3 * p ** mpf("1.5") + mpf("0.5") * sqrt(p) + zm12_lo + 1 / (24 * sqrt(p))  # zeta(-1/2) 구간 아래끝(값 자체는 50자리 아래)
    R2 = mpf(15) / 8 * C * n ** mpf("2.5") * H / (kk ** mpf("3.5") * k ** (mpf(2) / 3))
    D1 = x - k ** (-mpf(2) / 3)
    D2 = kk * sqrt(2 / pi) / sqrt(p) / k ** (mpf(2) / 3)
    cpsi = -z12_lo + z32_hi / 12
    Psilow = C * (2 * sqrt(p) - cpsi + 1 / (2 * sqrt(p)) - p ** mpf("-1.5") / 24)
    D3 = mpf("1.5") * kk * Psilow / ((n + 1) * k ** (mpf(2) / 3))
    return (E - R1 - R2) / (D1 + D2 - D3)


