# G7b: 7.6–7.7의 수치 상수 재계산 (정리 H*, W, 보조정리 threshold-unit-ratio)
from math import *
out = {}
# 보조정리 explicit-bounds (가)
out['(2pi)^-1/2 e^-1/12'] = (2*pi)**-0.5*exp(-1/12)
out['0.8/sqrt2000'] = 0.8/sqrt(2000)
# H* 기저 (ㄱ)
k=2000
out['H* (ㄱ)'] = (0.2-1/(2*k)-4/k**2)*k/(k+1)
# (ㄴ)
U1p1 = (0.8*k)**(2/3)+1
fl = 1-0.8/sqrt(2)-U1p1*(1/(2*k)+4/k**2)
out['H* (ㄴ) fl'] = fl
out['H* (ㄴ) k/(m+1)'] = 1/(1+U1p1/k)
out['H* (ㄴ) prod'] = fl/(1+U1p1/k)
# (ㄷ) m=2000
m=2000
fl3 = 1-0.8*(0.2*m)**(-1/3)-((0.2*m)**(2/3)+1)*(1/(2*m*(1-0.342*m**(-1/3)))+4/m**2)
out['H* (ㄷ) fl(2000)'] = fl3
out['H* (ㄷ) /4.0005'] = fl3/4.0005
# 귀납 w=4
w=4.0
st = 1.1/(w-1)**2+0.3355/(w*(w-1))
lhs = 0.98211*((1-st)*0.999875/0.14-1)
rhs = 2.2*w/(w-1)*(1+1.5/(w-1)+0.000125)
out['(7.27) lhs w=4'] = lhs; out['(7.27) rhs w=4'] = rhs
out['15*1.000125/sqrt2000'] = 15*1.000125/sqrt(2000)
# W (가)
out['1-0.8/sqrt301'] = 1-0.8/sqrt(301)
out['0.9538/0.398943'] = 0.9538/0.398943
# W (나)
k=3131
out['D_k(2)'] = 0.08329*sqrt(k)-2-42.14/k
J = k**(1/6)
out['J'] = J
out['D_k(wmax) lower'] = 0.33316*(J**3-2*J+1/J)-1.0005*J**2-1.0145
out['deriv at J'] = 0.33316*(3*J**2-2-J**-2)-2.001*J
out['(1+1/k)^(4/3)'] = (1+1/k)**(4/3)
out['0.14*2.38*0.9999'] = 0.14*2.38*0.9999
# threshold-unit-ratio k=6667
k=6667
j0 = floor(0.3*k)
out['j0'] = j0
val = -(0.3*k-1)*(0.3*k)/(2*(1.3*k+1))
out['-(0.3k-1)(0.3k)/(2(1.3k+1))'] = val
out['1+1.5 log k + val'] = 1+1.5*log(k)+val
exact = -sum(j*1.0/(k+1+j) for j in range(1,j0+1))
out['exact sum bound'] = exact
out['e^0.3'] = exp(0.3)
out['e^(3/(2k))'] = exp(3/(2*k))
out['1.00023*1.34986'] = 1.00023*1.34986
out['2*0.7654-1.3502'] = 2*0.7654-1.3502
# n^flat: 1003/e
out['1003/e'] = 1003/e
# polar-PD numbers (7.5, 범위 밖이지만 src-plus가 기댐)
out['2e^{-5.3146*0.6996}'] = 2*exp(-5.3146*0.6996)
out['0.3^1.5/2'] = 0.3**1.5/2
for kk,v in out.items(): print(f'{kk:40s} {v:.6f}')
