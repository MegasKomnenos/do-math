"""ZV5: 부록D_장5A.md D.critical-window-rig 에 넣은 중간 서술(F6 전 실행임을 밝힌 괄호)이
검토_외부피드백_1116_ZV1_D문장.py --apply 의 네 정규식이 바꾸는 구간 안에 들어 있어 재실행 뒤 자동으로 지워지는지 확인한다.
파일을 바꾸지 않고 일치 구간만 출력한다. python -I 로 실행."""
import re, os
ROOT = r"C:\math\임시\주차함수_증명"
s = open(os.path.join(ROOT, '장v2', '부록D_장5A.md'), encoding='utf-8').read()
pats = [
    (r'\*\*결과\.\*\* 모든 상자·셀\(\$1\{,\}892\$개\)의 여유가 양수다\..*?나머지 상자에서 \$[0-9.]+\$ 이상이다\.', re.S, '결과'),
    (r'이 글을 쓰며 위의 알고리즘을 그대로 구현한 하나의 코드로 \$44\$개 상자를 모두 다시 돌렸다\(.*?크다\.', re.S, '재실행 문장'),
    (r'상자 A29, G06, G07, G08, G13의 첫 셀은 \$\\mathrm\{cw\}=0\.2\$에서 통과한 것\(여유 [^)]*\)에 더해, ', 0, '재인증 괄호 1'),
    (r'최소 여유 각각 \$[0-9.]+\$, \$[0-9.]+\$, \$[0-9.]+\$, \$[0-9.]+\$, \$[0-9.]+\$; 다섯 번 합쳐 \$[0-9.]+\$시간', 0, '재인증 괄호 2'),
]
allok = True
for pat, fl, name in pats:
    ms = list(re.finditer(pat, s, fl))
    print(f"[{name}] 일치 {len(ms)}개")
    for m in ms:
        t = m.group(0)
        print("   시작:", t[:70].replace('\n', ' '), "…")
        print("   끝  :", "…", t[-60:].replace('\n', ' '))
        print("   길이:", len(t), "; 중간 서술 포함:", '바로잡기 전의 코드로 돌린 것이라' in t)
    allok &= len(ms) == 1
print("네 정규식 모두 정확히 한 번 일치:", allok)
print("중간 서술이 「재실행 문장」 구간 안에만 있음:", s.count('바로잡기 전의 코드로 돌린 것이라') == 1)
