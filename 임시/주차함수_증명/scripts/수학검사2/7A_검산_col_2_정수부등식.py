"""부록 D 15행·본문 342행: 정수 부등식 10^21*400^10 > 17^21*123^10 과 자릿수 사슬, 336-338행의 상수."""
from fractions import Fraction as F
import mpmath as mp

L = 10 ** 21 * 400 ** 10
R = 17 ** 21 * 123 ** 10
print("left  =", L, "digits", len(str(L)), "= %.6e" % L)
print("right =", R, "digits", len(str(R)), "= %.6e" % R)
print("left > right:", L > R)
print("left == 1048576*10^41:", L == 1048576 * 10 ** 41, "; left > 1.04e47:", F(L) > F(104, 100) * 10 ** 47)
print("17^4 =", 17 ** 4, "< 8.36e4:", 17 ** 4 < 83600)
print("8.36^5 =", F(836, 100) ** 5, "= %.4f" % float(F(836, 100) ** 5), "< 40836:", F(836, 100) ** 5 < 40836)
print("17*40836 =", 17 * 40836, "< 6.95e5:", 17 * 40836 < 695000, "; 17^21 =", 17 ** 21, "< 6.95e25:", F(17 ** 21) < F(695, 100) * 10 ** 25)
print("123^2 =", 123 ** 2, "< 1.513e4:", 123 ** 2 < 15130)
print("1.513^5 = %.5f" % float(F(1513, 1000) ** 5), "< 7.93:", F(1513, 1000) ** 5 < F(793, 100), "; 123^10 =", 123 ** 10, "< 7.93e20:", F(123 ** 10) < F(793, 100) * 10 ** 20)
print("6.95*7.93 =", F(695, 100) * F(793, 100), "< 55.2:", F(695, 100) * F(793, 100) < F(552, 10), "; right < 5.52e46:", F(R) < F(552, 100) * 10 ** 46)
# equivalence (40/41)(10/17)^{21/10} > 3/10  <=> 10^21 400^10 > 17^21 123^10
mp.mp.dps = 40
lhs = mp.mpf(40) / 41 * (mp.mpf(10) / 17) ** (mp.mpf(21) / 10)
print("(40/41)(10/17)^2.1 =", lhs, "> 0.3:", lhs > mp.mpf(3) / 10)
print("phi#(17/10) lower bound = 17/10 + above - 2 =", mp.mpf(17) / 10 + lhs - 2)
# o_k for k=41: -2log(1-1/k)/log(1+1/k) <= 2(k+1)/(k-1) <= 21/10
for k in (41, 42, 100, 121, 500):
    ok = -2 * mp.log(1 - mp.mpf(1) / k) / mp.log(1 + mp.mpf(1) / k)
    print(f"k={k}: o_k={ok}, 2(k+1)/(k-1)={mp.mpf(2*(k+1))/(k-1)}, o_k<=2(k+1)/(k-1): {ok <= mp.mpf(2*(k+1))/(k-1)}, <=2.1: {ok <= mp.mpf(21)/10}, >2: {ok > 2}")
print("1 - 2.1*(10/17)^3 =", 1 - mp.mpf(21) / 10 * (mp.mpf(10) / 17) ** 3)
