# 검토전체23 R4: 장5B의 수치 상수 재계산 (mpmath 50자리)
from mpmath import mp, mpf, sqrt, pi, exp, floor

mp.dps = 50


def show(name, val, bound, sense):
    ok = (val <= bound) if sense == '<=' else (val >= bound)
    print(f"{name}: {mp.nstr(val, 12)} {sense} {bound}  {'OK' if ok else 'FAIL'}")


n = mpf(50001)
T3 = mpf(1) / 3
T23 = mpf(2) / 3
H = mpf('1.5')

print('--- joining-width')
v = mpf(20001) ** T3
show('v=20001^(1/3) >= 27', v, 27, '>=')
show('1/3+2/(3v^2) <= 0.34', T3 + 2 / (3 * v * v), mpf('0.34'), '<=')
show('10((n+1)/2)^(2/3) - (6n^(2/3)+2) > 0', 10 * ((n + 1) / 2) ** T23 - (6 * n ** T23 + 2), 0, '>=')
show('6n^(2/3) - ((n-1)^(2/3)+1) > 0', 6 * n ** T23 - ((n - 1) ** T23 + 1), 0, '>=')

print('--- absorption (old-5-30)')
c = 1 / sqrt(2 * pi)
E = exp(1 / (12 * (n + 1)))
show('top_pi (y<=2n/3)', c * sqrt(2) * 3 ** H * (1 + 1 / n) ** H * n ** mpf('-0.5') * E, mpf('0.0132'), '<=')
show('(0.15)^1.5 <= 0.0581', mpf('0.15') ** H, mpf('0.0581'), '<=')
show('top_pi (y>2n/3)', c * mpf('0.0581') * (1 + 1 / n) ** H * E, mpf('0.0232'), '<=')
show('pi_n(n-1) bound < 0.1354', exp(-2) * ((n + 1) / (n - 1)) ** H * E, mpf('0.1354'), '<=')
show('e^-1-0.1354-0.0232 > 0.2', exp(-1) - mpf('0.1354') - mpf('0.0232'), mpf('0.2'), '>=')

print('--- landing mass')
a = mpf('1.15')
show('1.15^(2/3)+2.3(1.15^(-1/3)-6^(-1/2)) <= 2.3541', a ** T23 + mpf('2.3') * (a ** (-T3) - 6 ** mpf('-0.5')), mpf('2.3541'), '<=')
show('2.3(sqrt6-1.15^(1/3)) <= 3.2242', mpf('2.3') * (sqrt(6) - a ** T3), mpf('3.2242'), '<=')
show('1-1.15/6^1.5 >= 0.9217', 1 - a / 6 ** H, mpf('0.9217'), '>=')
show('3.2242-36*1.15/6^1.5 <= 0.4074', mpf('3.2242') - 36 * a / 6 ** H, mpf('0.4074'), '<=')
u = mpf(25000) ** T3
show('u=25000^(1/3) > 29.24', u, mpf('29.24'), '>=')
show('2.3541/u <= 0.0806', mpf('2.3541') / u, mpf('0.0806'), '<=')
show('0.4074/u^2 <= 0.0005', mpf('0.4074') / u ** 2, mpf('0.0005'), '<=')
show('2/u^3 <= 0.0001', 2 / u ** 3, mpf('0.0001'), '<=')
show('final landing >= 0.84', mpf('0.9217') - mpf('0.0806') - mpf('0.0005') - mpf('0.0001'), mpf('0.84'), '>=')
show('6*25000^(2/3)+1 <= 25000', 6 * mpf(25000) ** T23 + 1, 25000, '<=')
Y = 25000
qm = int(floor(6 * mpf(Y) ** T23))
s = mpf(0)
for q in range(1, qm):
    s += min(mpf(1), a * (Y + q + 1) / mpf(q + 1) ** H)
val = 1 - mpf(2) / Y - (1 - mpf(qm + 1) / Y) * a * (Y + qm + 1) / mpf(qm + 1) ** H - s / Y
show('landing first-ineq RHS at Y=25000 (>=4/5)', val, mpf('0.8'), '>=')

print('--- band inequality')


def hvc(ch):
    return 2 / sqrt(pi) * (1 + 1 / mpf(ch)) + 1 / sqrt(pi)


show('hv_5000 <= 0.02394', hvc(5000) / sqrt(5000), mpf('0.02394'), '<=')
show('3*0.02394 <= 0.0719', 3 * mpf('0.02394'), mpf('0.0719'), '<=')
show('sqrt(2/pi)/sqrt(5000) <= 0.01129', sqrt(2 / pi) / sqrt(5000), mpf('0.01129'), '<=')
w23 = (2 * n / 3) ** T23
pib = c * ((n + 1) / ((n / 2) * (n / 3 - 1 - w23))) ** H * E
show('pi_n(t0-1) bound <= 5.775e-7', pib, mpf('5.775e-7'), '<=')
show('0.15n*5.775e-7 <= 0.00434', mpf('0.15') * n * mpf('5.775e-7'), mpf('0.00434'), '<=')
show('1-0.01129-0.00434 >= 0.9843', 1 - mpf('0.01129') - mpf('0.00434'), mpf('0.9843'), '>=')
den = mpf('0.4') * n / 3 - 6 * w23 + 1
show('0.4n/3-6(2n/3)^(2/3)+1 >= 453', den, 453, '>=')
c4 = 1 / (12 * mpf(453)) + 1 / (12 * mpf(25000)) + 1 / (12 * mpf(50002))
show('c4 <= 0.00019', c4, mpf('0.00019'), '<=')
show('e^-0.00019 >= 0.9998', exp(-mpf('0.00019')), mpf('0.9998'), '>=')
show('0.4n/3 - (6(2n/3)^(2/3)+1) >= 0', mpf('0.4') * n / 3 - (6 * w23 + 1), 0, '>=')
show('n/3 - 10(2n/3)^(2/3) >= 0', n / 3 - 10 * w23, 0, '>=')
wb = w23 + 2
show('(1+3(n/2)^(-2/3))^1.5 <= 1.0053', (1 + 3 * (n / 2) ** (-T23)) ** H, mpf('1.0053'), '<=')
show('(n/3+1)/(n/3-wb) <= 1.0665', (n / 3 + 1) / (n / 3 - wb), mpf('1.0665'), '<=')
show('(1+2wb/n)^1.5 <= 1.0630', (1 + 2 * wb / n) ** H, mpf('1.0630'), '<=')
e0 = H * wb / (n / 2 + wb - 1) * (n / 3 + 2 * wb) / (n / 3 + 1 - wb)
show('eps0 <= 0.0717', e0, mpf('0.0717'), '<=')
pre = c * mpf('1.0053') * mpf('1.0665') * mpf('1.0630') * exp(mpf('0.0717') + 1 / mpf(300006))
show('prefactor <= 0.4885', pre, mpf('0.4885'), '<=')
show('0.4885*2wb/n <= 0.0203', mpf('0.4885') * 2 * wb / n, mpf('0.0203'), '<=')
show('0.9281*0.8*0.9998*1.9554 >= 1.4515', mpf('0.9281') * mpf('0.8') * mpf('0.9998') * mpf('1.9554'), mpf('1.4515'), '>=')
show('0.7 n/3 - ((2n/3)^(2/3)+2) >= 0', mpf('0.7') * n / 3 - (w23 + 2), 0, '>=')

print('--- right part')
y0 = mpf(33334)
show('10*33334^(2/3)-1 > 10356', 10 * y0 ** T23 - 1, 10356, '>=')
show('0.2*10357-7.3 >= 2064', mpf('0.2') * 10357 - mpf('7.3'), 2064, '>=')
show('e^-c4 right >= 0.9936', exp(-(mpf(1) / 156 + 1 / (12 * y0) + 1 / (12 * mpf(50002)))), mpf('0.9936'), '>=')
show('hv coefficient at 2064 <= 1.6932', hvc(2064), mpf('1.6932'), '<=')
t = y0 ** T3
show('eps_hov right <= 0.1573', mpf('1.6932') * (t / 10 + 1) / sqrt(2 * t * t - mpf('7.5')), mpf('0.1573'), '<=')
show('sqrt(2/pi)/sqrt(2064) <= 0.01757', sqrt(2 / pi) / sqrt(2064), mpf('0.01757'), '<=')
show('0.9(r+1)-2 - 0.8998(r+1) >= 0 at r+1=10358', mpf('0.9') * 10358 - 2 - mpf('0.8998') * 10358, 0, '>=')
show('1.5+1/33334 <= 1.50003', H + 1 / y0, mpf('1.50003'), '<=')
k = c * (mpf('1.50003') / mpf('0.8998')) ** H
print('  (2pi)^-1/2 (1.50003/0.8998)^1.5 =', mp.nstr(k, 10))
show('... * e^(1/(12*50002)) <= 0.8588', k * exp(1 / (12 * mpf(50002))), mpf('0.8588'), '<=')
show('0.3*0.8588 <= 0.25764', mpf('0.3') * mpf('0.8588'), mpf('0.25764'), '<=')
show('0.25764/sqrt(10358) <= 0.00254', mpf('0.25764') / sqrt(10358), mpf('0.00254'), '<=')
show('1-0.01757-0.00254 >= 0.9798', 1 - mpf('0.01757') - mpf('0.00254'), mpf('0.9798'), '>=')
r = mpf(10357)
widb = mpf('0.1') * (r + 1) + 2
show('(r+1)/(r-wid) <= 1.1116', (r + 1) / (r - widb), mpf('1.1116'), '<=')
show('(1+3y^(-2/3))^1.5 <= 1.0044', (1 + 3 * y0 ** (-T23)) ** H, mpf('1.0044'), '<=')
show('1.5wid/(r+1-wid) <= 0.1671', H * widb / (r + 1 - widb), mpf('0.1671'), '<=')
show('(1+(y^(2/3)+2)/y)^1.5 <= 1.0472', (1 + (y0 ** T23 + 2) / y0) ** H, mpf('1.0472'), '<=')
winr = c * mpf(2) / 3 * mpf('1.0044') * H * mpf('1.1116') * mpf('1.0472') * exp(mpf('0.1671') + 1 / mpf(400008))
show('(r+1)/y win <= 0.5513', winr, mpf('0.5513'), '<=')
show('0.8427*0.8*0.9936*1.9364-0.5513 >= 0.7457', mpf('0.8427') * mpf('0.8') * mpf('0.9936') * mpf('1.9364') - mpf('0.5513'), mpf('0.7457'), '>=')
show('0.7457*2/3 >= 0.4971', mpf('0.7457') * 2 / 3, mpf('0.4971'), '>=')
