from mpmath import mp, mpf, sqrt, exp, log, pi

mp.dps = 60
res = []


def chk(name, lhs, rel, rhs):
    lhs, rhs = mpf(lhs), mpf(rhs)
    ok = {'<=': lhs <= rhs, '<': lhs < rhs, '>=': lhs >= rhs, '>': lhs > rhs}[rel]
    res.append((ok, name, lhs, rel, rhs))
    print(('OK  ' if ok else 'FAIL'), name, '|', mp.nstr(lhs, 12), rel, mp.nstr(rhs, 12),
          '| 차', mp.nstr(rhs - lhs, 6))


n0 = mpf(50001)
c = (2 * pi) ** mpf('-0.5')

print('--- 보조정리 old-5-30 증명 ---')
chk('5-30: (2pi)^-1/2 sqrt2 3^{3/2}(1+1/n)^{3/2} n^{-1/2} e^{1/(12(n+1))} <= 0.0133 (n=50001)',
    c * sqrt(2) * mpf(3) ** mpf('1.5') * (1 + 1 / n0) ** mpf('1.5') * n0 ** mpf('-0.5') * exp(1 / (12 * (n0 + 1))),
    '<=', '0.0133')
chk('5-30: (1.5/10)^{3/2} <= 0.0581', (mpf('1.5') / 10) ** mpf('1.5'), '<=', '0.0581')
chk('5-30: (2pi)^-1/2 * 0.0581 * (1+1/n)^{3/2} e^{1/(12(n+1))} <= 0.0232',
    c * mpf('0.0581') * (1 + 1 / n0) ** mpf('1.5') * exp(1 / (12 * (n0 + 1))), '<=', '0.0232')
chk('5-30: e^-2 ((n+1)/(n-1))^{3/2} e^{1/(12(n+1))} < 0.1354',
    exp(-2) * ((n0 + 1) / (n0 - 1)) ** mpf('1.5') * exp(1 / (12 * (n0 + 1))), '<', '0.1354')
chk('5-30: e^-1 - 0.1354 - 0.0232 > 0.2', exp(-1) - mpf('0.1354') - mpf('0.0232'), '>', '0.2')

print('--- 보조정리 stop-lower 증명 ---')
chk('stop-lower: 1.5*0.95^{-5/2} <= 1.706', mpf('1.5') * mpf('0.95') ** mpf('-2.5'), '<=', '1.706')
U0 = mpf(25000)
chk('stop-lower: e^{1/(12U)} <= 1+1/(11U) (U=25000)', exp(1 / (12 * U0)), '<=', 1 + 1 / (11 * U0))
chk('stop-lower: (1+1.706*0.05)/11 <= 0.099', (1 + mpf('1.706') * mpf('0.05')) / 11, '<=', '0.099')
chk('stop-lower: 0.099 <= (2-1.706)*1  (i>=1: (1.706i+0.099)/U <= 2i/Y)', mpf('0.099'), '<=', mpf(2) - mpf('1.706'))
chk('stop-lower: (0.8^{-3/2}-1)/0.2 <= 1.988', (mpf('0.8') ** mpf('-1.5') - 1) / mpf('0.2'), '<=', '1.988')
chk('stop-lower: (1+1.988*0.2)/11 <= 0.128', (1 + mpf('1.988') * mpf('0.2')) / 11, '<=', '0.128')
chk('stop-lower: 0.128 <= (2-1.988)*1250  (i>=1250)', mpf('0.128'), '<=', (2 - mpf('1.988')) * 1250)
chk('stop-lower: 4/sqrt(2pi) < 1.596', 4 / sqrt(2 * pi), '<', '1.596')

print('--- 5.5.6 척도 변수 (h0, upsilon_max, c2) ---')
h0 = mpf('0.0342')
chk('h0: 0.0342^3 >= 1/25000', h0 ** 3, '>=', mpf(1) / 25000)
ups = sqrt(6 * h0)
c2 = 1 / (2 * (1 - ups))
print('   upsilon_max =', mp.nstr(ups, 12), ' c2 =', mp.nstr(c2, 12))

print('--- 보조정리 scaled-integrand (마) ---')
c3 = 1 / sqrt(2) - ups / 3
chk('(마): c3 = 1/sqrt2 - upsilon_max/3 >= 0.556', c3, '>=', '0.556')
chk('(마): 12^{3/2} >= 41.5', mpf(12) ** mpf('1.5'), '>=', '41.5')
chk('(마): sqrt2(1+6h0)*12/0.556 <= 36.8', sqrt(2) * (1 + 6 * h0) * 12 / mpf('0.556'), '<=', '36.8')
chk('(마): 0.556*41.5-12-log(36.8) > 7', mpf('0.556') * mpf('41.5') - 12 - log(mpf('36.8')), '>', '7')
chk('(마): f-prime(12) = 1.5*0.556*sqrt12 - 1 - 1/12 > 0', mpf('1.5') * mpf('0.556') * sqrt(12) - 1 - mpf(1) / 12, '>', '0')

print('--- 5.5.2 ---')
y0 = mpf(25000)
chk('5.5.2: 0.75(1.1y)^{2/3}+1 <= 0.1y (y=25000)', mpf('0.75') * (mpf('1.1') * y0) ** (mpf(2) / 3) + 1, '<=', mpf('0.1') * y0)
chk('5.5.2: 10((n+1)/2)^{2/3} > 6n^{2/3}+2 (n=50001)', 10 * ((n0 + 1) / 2) ** (mpf(2) / 3), '>', 6 * n0 ** (mpf(2) / 3) + 2)
chk('5.5.2: 6n^{2/3}+1 > 1+0.75(n-1)^{2/3}', 6 * n0 ** (mpf(2) / 3) + 1, '>', 1 + mpf('0.75') * (n0 - 1) ** (mpf(2) / 3))

print('--- 명제 band-inequality 조건 ---')
yb = 2 * n0 / 3
chk('band: 0.4n/3 >= 6(2n/3)^{2/3}+1', mpf('0.4') * n0 / 3, '>=', 6 * yb ** (mpf(2) / 3) + 1)
chk('band: 0.75(1.1*2n/3)^{2/3}+1 <= 0.7 n/3', mpf('0.75') * (mpf('1.1') * yb) ** (mpf(2) / 3) + 1, '<=', mpf('0.7') * n0 / 3)

print('--- 보조정리 right-part 증명 ---')
y = mpf(33334)
y23 = y ** (mpf(2) / 3)
y13 = y ** (mpf(1) / 3)
print('   y^{2/3} =', mp.nstr(y23, 12), ' 10y^{2/3}-1 =', mp.nstr(10 * y23 - 1, 12))
chk('rp: 10y^{2/3}-1 >= 10356', 10 * y23 - 1, '>=', '10356')
chk('rp: 10y^{2/3} >= 10357  (r+1 > 10y^{2/3} 이므로 정수 r+1 >= 10358, r >= 10357)', 10 * y23, '>=', '10357')
chk('rp[적힌 대로, r>=10356]: 0.2*10356-7.3 >= 2064', mpf('0.2') * 10356 - mpf('7.3'), '>=', '2064')
chk('rp[r>=10357]: 0.2*10357-7.3 >= 2064', mpf('0.2') * 10357 - mpf('7.3'), '>=', '2064')
c4 = mpf(1) / 156 + 1 / (12 * y) + 1 / (12 * (n0 + 1))
chk('rp: e^{-c4} >= 0.9936 (c4 = 1/156+1/(12*33334)+1/(12*50002))', exp(-c4), '>=', '0.9936')
chi = mpf(2064)
hv_coef = 2 / sqrt(pi) * (1 + 1 / chi) + 1 / sqrt(pi)
chk('rp: 2/sqrt(pi)(1+1/2064)+1/sqrt(pi) <= 1.6932', hv_coef, '<=', '1.6932')
chk('rp: 0.2(10y^{2/3}-1)-7.3 >= 2y^{2/3}-7.5 (항등; 차 0)', mpf('0.2') * (10 * y23 - 1) - mpf('7.3'), '>=', 2 * y23 - mpf('7.5'))
eps_hov = mpf('1.6932') * (y13 / 10 + 1) * (2 * y23 - mpf('7.5')) ** mpf('-0.5')
chk('rp: 1.6932(y^{1/3}/10+1)(2y^{2/3}-7.5)^{-1/2} <= 0.1573 (y=33334)', eps_hov, '<=', '0.1573')
chk('rp: sqrt(2/pi)*2064^{-1/2} <= 0.01757', sqrt(2 / pi) / sqrt(chi), '<=', '0.01757')
chk('rp: 1-0.01757-0.00245 >= 0.9799', 1 - mpf('0.01757') - mpf('0.00245'), '>=', '0.9799')
chk('rp: 0.75*1.1^{2/3} <= 0.7993', mpf('0.75') * mpf('1.1') ** (mpf(2) / 3), '<=', '0.7993')
for rp1 in (10357, 10358):
    rp1 = mpf(rp1)
    chk('rp: (1-0.07993)(r+1)-1 >= 0.9199(r+1) (r+1=%d)' % int(rp1), (1 - mpf('0.07993')) * rp1 - 1, '>=', mpf('0.9199') * rp1)
chk('rp: (n+1)/y <= 1.50003  ((1.5y+1)/y, y=33334)', (mpf('1.5') * y + 1) / y, '<=', '1.50003')
v = c * (mpf('1.50003') / mpf('0.9199')) ** mpf('1.5')
print('   (2pi)^-1/2 (1.50003/0.9199)^{3/2} =', mp.nstr(v, 15))
chk('rp: 0.830709... 표기 — 값 >= 0.830709', v, '>=', '0.830709')
chk('rp: 0.830709... 표기 — 값 < 0.830710', v, '<', '0.830710')
chk('rp: v * e^{1/(12*50002)} <= 0.8308', v * exp(1 / (12 * (n0 + 1))), '<=', '0.8308')
chk('rp: 0.3*0.8308 <= 0.24924', mpf('0.3') * mpf('0.8308'), '<=', '0.24924')
for rp1 in (10357, 10358):
    chk('rp: 0.24924 (r+1)^{-1/2} <= 0.00245 (r+1=%d)' % rp1, mpf('0.24924') / sqrt(mpf(rp1)), '<=', '0.00245')
for rp1 in (10357, 10358):
    rp1 = mpf(rp1)
    rho0 = mpf('0.07993') * rp1 + 1
    chk('rp: 2rho0 <= r (r+1=%d)' % int(rp1), 2 * rho0, '<=', rp1 - 1)
    chk('rp: (r+1)/(r-rho0) <= 1.0872 (r+1=%d)' % int(rp1), rp1 / (rp1 - 1 - rho0), '<=', '1.0872')
    chk('rp: 1.5rho0/(r+1-rho0) <= 0.1305 (r+1=%d)' % int(rp1), mpf('1.5') * rho0 / (rp1 - rho0), '<=', '0.1305')
rho0y = mpf('0.7993') * y23 + 1
chk('rp: (0.7993 y^{2/3}+2)^{3/2} <= 0.7172 y (y=33334)', (rho0y + 1) ** mpf('1.5'), '<=', mpf('0.7172') * y)
print('   (0.7993y^{2/3}+2)^{3/2}/y =', mp.nstr((rho0y + 1) ** mpf('1.5') / y, 12))
chk('rp: (1+rho0/y)^{3/2} <= 1.0376 (rho0 = 0.7993y^{2/3}+1)', (1 + rho0y / y) ** mpf('1.5'), '<=', '1.0376')
W = c * (mpf(2) / 3) * mpf('0.7172') * mpf('1.5') * mpf('1.0872') * mpf('1.0376') * exp(mpf('0.1305') + mpf(1) / 400008)
chk('rp: (2pi)^-1/2 (2/3) 0.7172*1.5*1.0872*1.0376 e^{0.1305+1/400008} <= 0.3678', W, '<=', '0.3678')
chk('rp: 1-0.1573 >= 0.8427 (표기 확인)', 1 - mpf('0.1573'), '>=', '0.8427')
chk('rp: 2*0.9799-0.0232 >= 1.9366 (표기 확인)', 2 * mpf('0.9799') - mpf('0.0232'), '>=', '1.9366')
P = mpf('0.8427') * mpf('0.71216') * mpf('0.9936') * mpf('1.9366') - mpf('0.3678')
chk('rp: 0.8427*0.71216*0.9936*1.9366-0.3678 >= 0.7869', P, '>=', '0.7869')
chk('rp: 1/n <= 2.5e-5', 1 / n0, '<=', '2.5e-5')
chk('rp: 0.7869*(2/3) >= 0.5246', mpf('0.7869') * 2 / 3, '>=', '0.5246')
chk('rp: 1-2/3 <= 0.3334', 1 - mpf(2) / 3, '<=', '0.3334')
chk('rp: 0.5246-0.3334-0.0001 > 0.191', mpf('0.5246') - mpf('0.3334') - mpf('0.0001'), '>', '0.191')
print('   결론의 참 여유: lambda=2/3에서 0.7869*2/3 - 1/3 - 2.5e-5 =',
      mp.nstr(mpf('0.7869') * 2 / 3 - mpf(1) / 3 - mpf('2.5e-5'), 10))

