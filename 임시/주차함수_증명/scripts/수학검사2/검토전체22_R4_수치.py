def chk(name, val, bound, sense):
    if sense == "<=":
        ok = val <= bound
    elif sense == ">=":
        ok = val >= bound
    elif sense == "<":
        ok = val < bound
    else:
        ok = val > bound
    print(("OK   " if ok else "FAIL ") + name + ": " + format(val, ".10f") + " " + sense + " " + str(bound))


