def chk(name, val, bound, kind):
    if kind == "<=":
        ok = val <= bound
    elif kind == ">=":
        ok = val >= bound
    elif kind == "<":
        ok = val < bound
    else:
        ok = val > bound
    print(("OK  " if ok else "FAIL"), name, mp.nstr(val, 12), kind, bound)


