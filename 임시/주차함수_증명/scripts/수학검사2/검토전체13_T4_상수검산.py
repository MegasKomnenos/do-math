# 5-20 ratio identity check numerically
from mpmath import binomial
def pin(n,t): return binomial(n,t)*mpf(t)**(t-1)*mpf(n-t+1)**(n-t-1)/mpf(n+1)**(n-1)
def g(x): return (x-1)*log(1+1/x)
n=25; t=15
p("pi_n(t+1)/pi_n(t) - e^{g(t)-g(n-t)} (n=25,t=15)", pin(n,t+1)/pin(n,t)-exp(g(mpf(t))-g(mpf(n-t))), "= 0")
# Bor formula vs pi
def Bor(m): return exp(-m)*mpf(m)**(m-1)/mp.factorial(m)
p("pi_25(15) - Bor(11)Bor(15)/Bor(26)", pin(25,15)-Bor(11)*Bor(15)/Bor(26), "= 0")
