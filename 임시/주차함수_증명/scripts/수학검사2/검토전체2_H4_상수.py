case1 = (2*pi)**-0.5*sqrt(2)*mpf(3)**1.5*(1+1/n)**1.5*n**-0.5*exp(1/(12*(n+1)))
print("5-30 y<=2n/3:", case1, "<=0.0133", case1 <= 0.0133)
c2 = (mpf(1.5)/10)**1.5
print("(0.15)^{3/2} =", c2, "<=0.0581", c2 <= 0.0581)
case2 = (2*pi)**-0.5*mpf('0.0581')*(1+1/n)**1.5*exp(1/(12*(n+1)))
print("5-30 y>2n/3:", case2, "<=0.0232", case2 <= 0.0232)
