print("e^-1 - 0.1354 - 0.0232 =", exp(-1)-mpf('0.1354')-mpf('0.0232'))
# 5.5.2 폭: 0.75*1.1^{2/3}
a = mpf('0.75')*mpf('1.1')**(mpf(2)/3)
