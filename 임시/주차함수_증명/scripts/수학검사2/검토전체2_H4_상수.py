hv = Qw**-0.5*(2/sqrt(pi)*(1+1/Qw)+1/sqrt(pi)); print("hv coefficient:", hv*Qw**0.5, "<=1.6932")
t = y**(mpf(1)/3)
eps = mpf('1.6932')*(t/10+1)*(2*t**2-mpf('7.5'))**-0.5; print("eps_hov:", eps, "<=0.1573", eps <= mpf('0.1573'))
print("sqrt(2/pi)/sqrt(2064):", sqrt(2/pi)/sqrt(2064))
rho = mpf('0.07993')*(r+1)+1
print("(r+1-rho)/(r+1):", (r+1-rho)/(r+1), ">=0.9199")
k1 = (2*pi)**-0.5*(mpf('1.50003')/mpf('0.9199'))**1.5*exp(1/(12*50002)); print("0.8308 check:", k1)
print("0.3*0.8308/sqrt(10357):", mpf('0.3')*mpf('0.8308')/sqrt(10357))
print("(r+1)/(r-rho):", (r+1)/(r-rho), "<=1.0872")
rho_y = mpf('0.7993')*y**(mpf(2)/3)+1
print("(rho_y+1)^{3/2}/y:", (rho_y+1)**1.5/y, "<=0.7172")
print("1.5 rho/(r+1-rho):", mpf('1.5')*rho/(r+1-rho), "<=0.1305")
print("(1+rho_y/y)^{3/2}:", (1+rho_y/y)**1.5, "<=1.0376")
W = (2*pi)**-0.5*mpf(2)/3*mpf('0.7172')*mpf('1.5')*mpf('1.0872')*mpf('1.0376')*exp(mpf('0.1305')+mpf(1)/400008)
print("W bound:", W, "<=0.3678", W <= mpf('0.3678'))
c4 = exp(-(mpf(1)/156+1/(12*y)+1/(12*50002))); print("e^-c4:", c4, ">=0.9936", c4 >= mpf('0.9936'))
psi = mpf('0.8427')*mpf('0.71216')*mpf('0.9936')*mpf('1.9366')-mpf('0.3678'); print("0.7869 check:", psi)
print("0.7869*2/3-0.3334-0.0001:", mpf('0.7869')*2/3-mpf('0.3334')-mpf('0.0001'))
