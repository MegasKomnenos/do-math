print("10((n+1)/2)^{2/3} =", 10*((n+1)/2)**(mpf(2)/3), " 6n^{2/3}+2 =", 6*n**(mpf(2)/3)+2)
# right-part
y = mpf(33334); r = mpf(10356)
print("r >= 10 y^{2/3}-1 :", 10*y**(mpf(2)/3)-1)
