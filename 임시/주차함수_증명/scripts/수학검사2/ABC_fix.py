total = 0
for fname, fixes in FIXES.items():
    path = os.path.join(ROOT, "장v2", fname)
    text = open(path, encoding="utf-8", newline="").read()
    changed = 0
    for old, new in fixes:
        c_old = text.count(old)
        c_new = text.count(new)
        if c_old == 0 and c_new >= 1:
            print(f"[{fname}] 이미 적용됨: {old[:50]}…")
            continue
        if c_old != 1:
            print(f"[{fname}] 앵커가 {c_old}번 나타남, 건너뜀: {old[:60]}…")
            continue
        text = text.replace(old, new)
        changed += 1
        print(f"[{fname}] 치환: {old[:60]}… → …{new[-30:]}")
    if changed:
        open(path, "w", encoding="utf-8", newline="").write(text)
    total += changed
    print(f"[{fname}] 치환 {changed}건")
print("총 치환", total)
