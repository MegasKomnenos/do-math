def apply(path, edits, protect=None):
    s = io.open(path, encoding="utf-8").read()
    if protect:
        p0 = s.index(protect[0]); p1 = s.index(protect[1])
    changed = 0
    for old, new in edits:
        n_old, n_new = s.count(old), s.count(new)
        if n_old == 0 and n_new == 1:
            print(f"이미 적용됨: {old[:60]!r}"); continue
        if n_old != 1:
            print(f"앵커 수 {n_old} != 1, 건너뜀: {old[:60]!r}"); continue
        pos = s.index(old)
        if protect and p0 <= pos < p1:
            print(f"moment-certification 블록 안, 건너뜀: {old[:60]!r}"); continue
        s = s.replace(old, new, 1); changed += 1
        print(f"치환: {old[:70]!r}\n   -> {new[:70]!r}")
    if changed:
        io.open(path, "w", encoding="utf-8", newline="\n").write(s)
    print(f"[{os.path.basename(path)}] 치환 수 {changed}")

