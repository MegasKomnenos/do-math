def tilt_sum_exact(k):
    # Σ_{n=2}^{k+1} Bor(n) q^n,  q = e (k/(k+1))^{k-1}  → Bor(n) q^n = n^{n-1}/n! · (k/(k+1))^{(k-1)n}
    x = Fraction(k, k + 1) ** (k - 1)
    s = Fraction(0)
    fact = 1
    for n in range(2, k + 2):
        fact = fact * n if n > 1 else 1
    s = Fraction(0)
    import math
    for n in range(2, k + 2):
        s += Fraction(n ** (n - 1), math.factorial(n)) * x ** n
    return s


