def rd(rel):
    with io.open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def wr(rel, s):
    with io.open(os.path.join(ROOT, rel), "w", encoding="utf-8", newline="") as f:
        f.write(s)


def main():
    applied = skipped = 0
    for rel, old, new, rule, why in EDITS:
        s = rd(rel)
        n_old, n_new = s.count(old), s.count(new)
        if n_new >= 1:          # 이미 적용(new가 old를 품는 경우도 포함)
            skipped += 1
            continue
        if n_old != 1:
            print(f"[중단] {rel}: 앵커가 {n_old}번 나타남(규칙 {rule}; {why}): {old[:70]}")
            sys.exit(1)
        wr(rel, s.replace(old, new))
        applied += 1
        print(f"[적용 {rule}] {rel}: {why}: {old[:40]} -> {new[:40]}")
    for rel, old, new, rule, expect in GLOBAL:
        s = rd(rel)
        n_old, n_new = s.count(old), s.count(new)
        if n_old == 0 and n_new >= expect:
            skipped += 1
            continue
        if n_old != expect:
            print(f"[중단] {rel}: 「{old}」 {n_old}회(예상 {expect})")
            sys.exit(1)
        wr(rel, s.replace(old, new))
        applied += n_old
        print(f"[적용 {rule}] {rel}: 「{old}」→「{new}」 {n_old}회")
    print(f"적용 {applied}, 이미 적용 {skipped}")


if __name__ == "__main__":
    main()
