#ifndef VIRTUAL_F_KEYBOARD_COMMON_H
#define VIRTUAL_F_KEYBOARD_COMMON_H

#define KEYBOARD_REPORT_ID 0x01
#define CONTROL_REPORT_ID  0x02

#define VIRTUAL_F_VID      0xCAFE
#define VIRTUAL_F_PID      0xF001
#define VIRTUAL_F_VERSION  0x0102

#define MAXIMUM_STRING_LENGTH         (126 * sizeof(WCHAR))
#define VHIDMINI_MANUFACTURER_STRING  L"Virtual F Keyboard Project"
#define VHIDMINI_PRODUCT_STRING       L"Virtual F Keyboard"
#define VHIDMINI_SERIAL_NUMBER_STRING L"VFK-0001"
#define VHIDMINI_DEVICE_STRING        L"Virtual F Keyboard UMDF Device"
#define VHIDMINI_DEVICE_STRING_INDEX  5

#include <pshpack1.h>

typedef struct _VIRTUAL_KEYBOARD_INPUT_REPORT {
    UCHAR ReportId;
    UCHAR Modifiers;
    UCHAR Reserved;
    UCHAR Keys[6];
} VIRTUAL_KEYBOARD_INPUT_REPORT, *PVIRTUAL_KEYBOARD_INPUT_REPORT;

typedef struct _VIRTUAL_KEYBOARD_LED_REPORT {
    UCHAR ReportId;
    UCHAR LedBits;
} VIRTUAL_KEYBOARD_LED_REPORT, *PVIRTUAL_KEYBOARD_LED_REPORT;

typedef struct _VIRTUAL_KEYBOARD_CONTROL_REPORT {
    UCHAR  ReportId;
    UCHAR  Enabled;
    USHORT IntervalMs;
} VIRTUAL_KEYBOARD_CONTROL_REPORT, *PVIRTUAL_KEYBOARD_CONTROL_REPORT;

#include <poppack.h>

#define KEYBOARD_INPUT_REPORT_SIZE_CB  ((USHORT)(sizeof(VIRTUAL_KEYBOARD_INPUT_REPORT) - 1))
#define KEYBOARD_LED_REPORT_SIZE_CB    ((USHORT)(sizeof(VIRTUAL_KEYBOARD_LED_REPORT) - 1))
#define CONTROL_FEATURE_REPORT_SIZE_CB ((USHORT)(sizeof(VIRTUAL_KEYBOARD_CONTROL_REPORT) - 1))

#endif
